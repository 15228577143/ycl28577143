def generate_exam_paper(today, q_list):
    content = f"""# 2026事业单位统考 公基+职测100题【试题卷】
> 生成时间：{today}
> 总题量：100题｜公共基础知识 60题，职业能力测验40题
> 使用说明：本卷为刷题试题，答案和详细解析在【解析卷.md】，点击链接跳转查看

"""
    for item in q_list:
        qid = item["id"]
        content += f"<a id=\"q{qid}\"></a>\n## 第{qid}题【{item['type']}】\n"
        content += f"{item['title']}\n\n"
        for opt in item["opts"]:
            content += f"{opt}\n"
        content += f"\n👉【查看答案解析】[解析卷.md#ans{qid}](解析卷.md#ans{qid})\n\n---\n\n"
    filename = f"2026事业单位统考_公基职测_试题卷.md"
    with open(filename, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"✅ 已生成试题卷：{filename}")


def generate_answer_paper(today, q_list):
    content = f"""# 2026事业单位统考 公基+职测100题【解析卷】
> 生成时间：{today}
> 配套试题卷：2026事业单位统考_公基职测_试题卷.md

"""
    for item in q_list:
        qid = item["id"]
        content += f"<a id=\"ans{qid}\"></a>\n## 第{qid}题【{item['type']}】\n"
        content += f"**答案：{item['ans']}**\n\n"
        content += f"解析：{item['explain']}\n\n"
        content += f"🔙【返回题目】[2026事业单位统考_公基职测_试题卷.md#q{qid}](2026事业单位统考_公基职测_试题卷.md#q{qid})\n\n---\n\n"
    filename = f"解析卷.md"
    with open(filename, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"✅ 已生成解析卷：{filename}")


